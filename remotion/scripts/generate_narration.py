import asyncio
from pathlib import Path
import edge_tts

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
SRC = ROOT / "src"
PUBLIC.mkdir(exist_ok=True)
TEXT = "看见闪电，是光先到达眼睛。\n听见雷声，是声音随后到达耳朵。\n这套字幕系统可以自动跟随中文配音。"
VOICE = "zh-CN-XiaoxiaoNeural"

async def main():
    communicate = edge_tts.Communicate(TEXT, VOICE, rate="-10%")
    audio = PUBLIC / "narration.mp3"
    sub = edge_tts.SubMaker()
    with audio.open("wb") as f:
        async for chunk in communicate.stream():
            if chunk["type"] == "audio":
                f.write(chunk["data"])
            elif chunk["type"] == "WordBoundary":
                sub.feed(chunk)
    srt = sub.get_srt()
    if not srt.strip() or audio.stat().st_size < 1000:
        raise RuntimeError("TTS produced empty audio or subtitles")
    (PUBLIC / "narration.srt").write_text(srt, encoding="utf-8")
    (SRC / "generated-narration.ts").write_text(
        "// Generated by scripts/generate_narration.py; do not edit.\n"
        + "export const narrationSrt = " + repr(srt).replace("\\n", "\\n") + ";\n",
        encoding="utf-8",
    )
    print("Generated narration", audio.stat().st_size, "bytes and SRT", len(srt))

if __name__ == "__main__":
    asyncio.run(main())
